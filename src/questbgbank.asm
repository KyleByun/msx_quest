;-----------------------------------------------------------------------------
; 배경 화면 RLE 만 담는 8KB 뱅크
;
; 벽면 자료가 블록 셋으로 늘면서(옆면 하나에 벽/정면/뚫림 세 가지) 본체 뱅크
; 0~2 (0x4000-0x9FFF) 에 6KB 짜리 배경까지 둘 자리가 없어졌다. 배경은 시작할 때
; 한 번만 푸는 자료라 0xA000 창으로 잠깐 불러 쓰기에 가장 알맞다.
;
; questspr*.asm 과 같은 방식이다 - 따로 어셈블해서 build_quest.ps1 이 롬 이미지의
; 제자리에 얹는다. 여기 심볼은 본체에서 보이지 않으므로, 끝 판정은 주소 대신
; questconst.asm 의 BG_RLE_LEN 으로 한다.
;-----------------------------------------------------------------------------

    DEVICE NOSLOT64K

    ORG 0xA000
    include "src/questbg.asm"

    ds 0xC000 - $, 0xFF
    SAVEBIN "build/questbgbank.bin", 0xA000, 0x2000
