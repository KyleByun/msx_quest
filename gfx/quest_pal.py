"""화면 전체가 함께 쓰는 16색 팔레트. 여기가 정본이다.

SCREEN 5 는 화면 하나에 팔레트 하나뿐이라, 배경·벽면·몬스터 그림·미니맵이 전부
이 16색 안에서 해결된다. 그래서 값을 한 칸이라도 바꾸면 배경 RLE 와 구운 벽면
픽셀이 통째로 달라진다 - 앞뒤 비교가 안 되므로 함부로 건드리지 않는다.

예전에는 quest_convert.py 와 quest_rules.py 가 같은 값을 각자 적어 두고 "서로
같아야 한다"는 주석만 달아 두었다. 한쪽만 고치면 조용히 어긋나므로 여기로 모았다.

값의 유래: 처음에는 배경과 벽면 픽셀을 한꺼번에 놓고 중앙값 분할로 뽑았다. 지금은
배경 정본(gfx/quest_bg.png)이 이미 16색으로 정해진 그림이라 다시 뽑는 것이
자기를 근거로 자기를 정하는 셈이어서, 그때 나온 결과를 그대로 고정했다.
"""

# RGB333 (V9938 의 채널당 3비트)
PAL333 = [
    (7, 7, 6),      # 0  양피지 크림
    (7, 7, 5),      # 1
    (7, 6, 5),      # 2
    (6, 6, 5),      # 3
    (5, 5, 5),      # 4  패널 회색 - 화면에서 제일 많이 쓴다
    (5, 5, 3),      # 5
    (4, 4, 4),      # 6  그늘
    (3, 3, 3),      # 7
    (2, 2, 2),      # 8
    (0, 0, 0),      # 9  검정
    (1, 1, 1),      # 10
    (6, 6, 6),      # 11
    (7, 7, 7),      # 12 흰색
    (7, 6, 4),      # 13
    (2, 3, 7),      # 14 파랑 - 미니맵의 내 위치 표시 (아래 설명)
    (5, 5, 2),      # 15
]

# 14 번은 원래 (5,4,5) 였다. 배경 54,272 픽셀 중 **한 픽셀도** 쓰지 않았고 구운
# 자료에서도 거의 안 나오던 자리라, 미니맵에서 내 위치를 표시할 파란색으로
# 바꿨다. 이 그림에는 파랑이 한 칸도 없어서(전부 회색과 크림) 어딘가는 내줘야
# 했는데, 바꿨을 때 실제로 달라지는 픽셀 수를 세어 보고 고른 자리다.
COL_HERO = 14

# 그림을 16색으로 줄일 때 **골라서는 안 되는** 자리.
#
# 파랑을 넣어 놓고 그냥 두었더니 몬스터 그림에 파란 점 네 개가 박혔다. 원래
# (5,4,5) 였던 자리를 쓰던 픽셀들이 있었는데, 색을 바꿨어도 여전히 그 자리가
# 제일 가깝다고 뽑힌 것이다. 배경과 벽면은 한 픽셀도 안 쓰고 있어서 눈치채지
# 못할 뻔했다. UI 전용 색은 양자화 후보에서 아예 빼는 것이 맞다.
RESERVED = frozenset({COL_HERO})


def to888(c):
    return tuple(round(v * 255 / 7) for v in c)


def nearest(pal, c):
    """색 c 에 가장 가까운 팔레트 번호. RESERVED 자리는 고르지 않는다."""
    best, bi = None, 0
    for i, p in enumerate(pal):
        if i in RESERVED:
            continue
        pp = to888(p)
        d = sum((pp[k] - c[k]) ** 2 for k in range(3))
        if best is None or d < best:
            best, bi = d, i
    return bi
