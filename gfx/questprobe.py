CONTROL = 6                     # 확실히 너무 빠른 것. 이건 **깨져야** 한다.
Z80_HZ = 3579545.0


def to332(c):
    """RGB333 -> GRB332 한 바이트. R 과 G 는 3 비트 그대로, B 만 4 단계로 준다.

    파랑은 3 비트(8 단계)에서 2 비트(4 단계)로 줄어든다. b>>1 이 아니라 눈금
    자체를 다시 재야 한다 - 4 단계의 눈금은 0, 7/3, 14/3, 7 이다.
    """
    r, g, b = c
    return (g << 5) | (r << 2) | int(round(b * 3.0 / 7.0))


def write_pal(_outdir):
    """src/questprobepal.asm - 팔레트 정본에서 뽑는다. 손으로 옮겨 적지 않는다."""
    L = ["; gfx/questprobe.py 가 gfx/quest_pal.py 에서 만든다. 직접 고치지 말 것.",
         ";",
         "; SCREEN 8 에는 팔레트가 없다. 색이 GRB332 로 못박혀 있어서 R 과 G 는",
         "; 3 비트가 그대로 가고 B 만 3 비트에서 2 비트로 준다.",
         "Pal332:"]
    for i, c in enumerate(quest_pal.PAL333):
        L.append("    db 0x%02X                     ; %2d  RGB333 %d,%d,%d"
                 % (to332(c), i, c[0], c[1], c[2]))
    path = os.path.join(HERE, "..", "src", "questprobepal.asm")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("wrote src/questprobepal.asm")
    return 0


def syms():
    out = {}
    for line in open(SYM, encoding="utf-8"):
        if ": EQU 0x" in line:
            name, val = line.split(": EQU 0x")
            out[name] = int(val.strip(), 16)
    return out


def write_tcl(outdir):
    S = syms()
    out = outdir.replace("\\", "/")
    L = ["# generated by gfx/questprobe.py",
         'set ::fh [open "%s/probe.txt" w]' % out,
         "set ::t0 0",
         "set ::c0 0",
         "set ::tf 0",
         # openMSX 21 은 too_fast_vram_access 를 real 로 흉내낸다. 픽셀이
         # 깨졌는지만 보지 말고, VDP 가 "너무 빠르다"고 알려 주는 것도 센다.
         # 인자를 받게 해 둔다. openMSX 가 인자를 붙여 부르면 인자 없는 proc 은
         # 조용히 오류가 나고, 그러면 "경고 0 번" 이 콜백이 안 불린 탓인지
         # 정말 안 걸린 탓인지 알 수가 없다.
         "proc tfva {args} { incr ::tf }",
         "set ::VDP.too_fast_vram_access_callback tfva",
         # 카나리아 - 확실히 너무 빠른 쓰기(3.35 us)가 정말 걸리는지 본다.
         "debug set_bp %d 1 { set ::tf 0 }" % S["CanaryStart"],
         "debug set_bp %d 1 {" % S["CanaryEnd"],
         '  puts $::fh "canary $::tf"',
         '  puts $::fh "cbset [set ::VDP.too_fast_vram_access_callback]"',
         "  flush $::fh",
         "}",
         # 같은 간격의 **읽기**. 여기서도 안 걸리면 이 고장 자체를 안 보는 것이다.
         "debug set_bp %d 1 { set ::tf 0 }" % S["CanaryRStart"],
         "debug set_bp %d 1 { puts $::fh \"canaryr $::tf\" ; flush $::fh }"
         % S["CanaryREnd"],
         # 명령 엔진이 도는 중에 같은 간격으로 쓰기.
         "debug set_bp %d 1 { set ::tf 0 }" % S["CanaryCStart"],
         "debug set_bp %d 1 { puts $::fh \"canaryc $::tf\" ; flush $::fh }"
         % S["CanaryCEnd"],
         # 같은 쓰기 카나리아를 GRAPHIC 4 에서도.
         "debug set_bp %d 1 { set ::tf 0 }" % S["Canary4Start"],
         "debug set_bp %d 1 {" % S["Canary4End"],
         '  puts $::fh "canary4 $::tf"',
         "  flush $::fh",
         "}",
         # VDP 명령 엔진으로 같은 넓이를 다루면 얼마나 걸리나.
         "debug set_bp %d 1 { set ::c0 [machine_info time] }" % S["HmmmStart"],
         "debug set_bp %d 1 {" % S["HmmmEnd"],
         '  puts $::fh "hmmm [expr [machine_info time] - $::c0]"',
         "  set ::c0 [machine_info time]",
         "  flush $::fh",
         "}",
         "debug set_bp %d 1 { puts $::fh \"hmmv [expr [machine_info time]"
         " - $::c0]\" ; flush $::fh }" % S["HmmvEnd"],
         # BlitStart 에서 시각을 잡고 BlitEnd 에서 뺀다. 롬 안에 시계를 넣는
         # 것보다 정확하고, 재는 코드가 재는 대상을 늦추지도 않는다.
         "debug set_bp %d 1 { set ::t0 [machine_info time] ; set ::tf 0 }"
         % S["BlitStart"],
         "debug set_bp %d 1 {" % S["BlitEnd"],
         "  set v [debug read memory %d]" % S["Variant"],
         "  puts $::fh \"time $v [expr [machine_info time] - $::t0] $::tf\"",
         "  flush $::fh",
         "}",
         "debug set_bp %d 1 {" % S["ProbeDone"],
         # 이 openMSX 에는 debug save_to_file 이 없다. read_block 은 바이트열을
         # 통째로 돌려주므로 파일로 직접 쓴다 - 5 만 번 debug read 를 도는 것보다
         # 비교가 안 되게 빠르다.
         '  set vf [open "%s/vram.bin" w]' % out,
         "  fconfigure $vf -translation binary",
         "  puts -nonewline $vf [debug read_block VRAM 0 %d]"
         % (VRAM_STRIDE * DUMP_ROWS),
         "  close $vf",
         "}",
         # 카나리아 셋은 덤프 뒤에 돈다(모드를 바꾸면 VRAM 배치가 어긋난다).
         "debug set_bp %d 1 { close $::fh ; exit }" % S["AllDone"],
         "after time 20 { close $::fh ; exit }"]      # 안전장치
    open(os.path.join(outdir, "probe.tcl"), "w",
         encoding="ascii", newline="\n").write("\n".join(L) + "\n")
    print("wrote probe.tcl")
    return 0


