def ref_tcl(outdir):
    import quest_sides
    q = {}
    for line in open(QUEST_SYM, encoding="utf-8"):
        if ": EQU 0x" in line:
            name, val = line.split(": EQU 0x")
            q[name] = int(val.strip(), 16)
    out = outdir.replace("\\", "/")
    L = ["# generated by gfx/questprobe.py",
         'set ::fh [open "%s/ref.txt" w]' % out,
         "set ::t0 0",
         "set ::case none",
         "set ::armed 0",
         # 런이 한 장에 몇 개인가. VDP 명령으로 그리려면 런마다 명령 하나가
         # 필요하고, 명령 하나에 드는 준비 시간(약 520 T = 0.15 ms)이 그 수만큼
         # 곱해진다. 이 수를 모르면 "VDP 에 시키면 빠르다"는 말을 할 수 없다.
         "set ::runs 0",
         "debug set_bp %d 1 { incr ::runs }" % q["RenderDungeon.run"],
         "debug set_bp %d 1 {" % q["RenderDungeon"],
         "  set ::t0 [machine_info time]",
         "  set ::runs 0",
         "  if {$::armed} { return }",
         "  set ::armed 1",
         "  set sp [reg sp]",
         "  set r [expr [debug read memory $sp] + 256 * [debug read memory"
         " [expr $sp + 1]]]",
         '  debug set_bp $r 1 { puts $::fh "ref $::case [expr'
         ' [machine_info time] - $::t0] $::runs" ; flush $::fh }',
         "}"]
    t = 7.0
    for name in REF_CASES:
        grid, px, py, f = quest_sides.CASES[name]
        w = ["debug write memory %d %d" % (q["MapDataRam"] + y * 16 + x,
                                           1 if grid[y][x] == "#" else 0)
             for y in range(16) for x in range(16)]
        w += ["debug write memory %d %d" % (q["posX"], px),
              "debug write memory %d %d" % (q["posY"], py),
              "debug write memory %d %d" % (q["facing"], f),
              "debug write memory %d 0" % q["BattleOn"],
              "debug write memory %d 1" % q["needDraw"]]
        L.append("after time %.2f { set ::case %s ; %s }"
                 % (t, name, " ; ".join(w)))
        t += 1.0
    L.append("after time %.2f { close $::fh ; exit }" % t)
    open(os.path.join(outdir, "ref.tcl"), "w",
         encoding="ascii", newline="\n").write("\n".join(L) + "\n")
    print("wrote ref.tcl (%s)" % ", ".join(REF_CASES))
    return 0


def ref_ms(outdir):
    """지도를 못박고 잰 SCREEN 5 기준값. {이름: ms}. 한 지도를 여러 번 재면
    같은 값이 나오므로 마지막 것을 쓴다."""
    path = os.path.join(outdir, "ref.txt")
    if not os.path.exists(path):
        return {}
    out = {}
    for line in open(path).read().split("\n"):
        if line.startswith("ref "):
            _, name, t, runs = line.split()
            if name != "none":
                out[name] = (float(t) * 1000.0, int(runs))
    return out


def check(outdir):
    times, canary, canary4, canaryr, canaryc, cbset = {}, -1, -1, -1, -1, ""
    cmd = {}
    for line in open(os.path.join(outdir, "probe.txt")).read().split("\n"):
        if line.startswith("time "):
            _, v, t, tf = line.split()
            times[int(v)] = (float(t), int(tf))
        elif line.startswith("canary "):
            canary = int(line.split()[1])
        elif line.startswith("canary4 "):
            canary4 = int(line.split()[1])
        elif line.startswith("canaryr "):
            canaryr = int(line.split()[1])
        elif line.startswith("canaryc "):
            canaryc = int(line.split()[1])
        elif line.startswith("cbset "):
            cbset = line.split(None, 1)[1].strip()
        elif line.startswith("hmmm ") or line.startswith("hmmv "):
            k, t = line.split()
            cmd[k] = float(t) * 1000.0
    vram = open(os.path.join(outdir, "vram.bin"), "rb").read()
    if len(vram) < VRAM_STRIDE * DUMP_ROWS:
        print("VRAM 덤프가 %d 바이트뿐이다" % len(vram))
        return 1

    def px(x, y):
        return vram[y * VRAM_STRIDE + x]

    bad = 0

    # ---- 1+2. 간격마다 걸린 시간과 흘린 바이트 -------------------------------
    print("변형  안쪽 고리          T/바이트    us     96x96     프레임  흘림  VDP경고")
    ok_var, lost_of = None, {}
    for v in range(NVAR):
        lost = first = 0
        for row in range(BAND_H):
            y = v * BAND_H + row
            for x in range(VIEW_W):
                if px(x, y) != x:
                    lost += 1
                    if lost == 1:
                        first = (x, y)
        lost_of[v] = lost
        t, tf = times.get(v, (float("nan"), -1))
        ms = t * 1000.0
        print("  %d   %-18s %5.1f T  %5.1f  %7.1f ms  %5.1f  %5d  %7d"
              % (v, VAR_NAME[v], VAR_T[v], VAR_T[v] / Z80_HZ * 1e6,
                 ms, ms / 16.67, lost, tf))
        if lost == 0 and tf == 0 and ok_var is None and v != CONTROL:
            ok_var = v

    # ---- 견줄 값과 어림 -----------------------------------------------------
    # 위 표의 84 ms 를 지금 것과 곧장 견주면 안 된다. 저것은 96x96 을 그냥 밀어
    # 넣은 값이고, 지금 RenderDungeon 은 가시성 계산과 런 해독까지 다 한다.
    # 옳게 견주는 방법: SCREEN 8 은 픽셀 수만 두 배(4,608 -> 9,216 바이트)이고
    # 나머지 일은 그대로다. 그러니 **늘어나는 것은 4,608 바이트 값어치뿐**이다.
    # ---- VDP 명령 엔진 -----------------------------------------------------
    # Z80 이 바이트를 미는 대신 VDP 에게 시키면, 벽면 자료를 롬이 아니라 VRAM 에
    # 둘 수 있다. SCREEN 8 페이지 0 이 64KB 라 128KB 중 64KB 가 남는다.
    if cmd:
        print("\n같은 넓이(96x96 = 9,216 픽셀)를 VDP 명령 엔진에 시키면")
        best = min(times[v][0] for v in range(NVAR)) * 1000.0
        for k, label in (("hmmm", "HMMM (VRAM 안에서 복사)"),
                         ("hmmv", "HMMV (단색 채우기)")):
            if k in cmd:
                print("   %-22s %6.1f ms   Z80 이 미는 것보다 %.1f 배 %s"
                      % (label, cmd[k], max(cmd[k], best) / min(cmd[k], best),
                         "빠르다" if cmd[k] < best else "느리다"))
        print("   (Z80 이 제일 빠른 간격으로 밀었을 때가 %.1f ms)" % best)

    ref = ref_ms(outdir)
    if ref:
        print("\n견줄 값: 지금 SCREEN 5 의 RenderDungeon (지도를 못박고 잰 값)")
        for name in REF_CASES:
            if name in ref:
                ms, runs = ref[name]
                print("   %-8s %6.1f ms (%.1f 프레임)   런 %d 개"
                      % (name, ms, ms / 16.67, runs))
        worst = max(v[0] for v in ref.values())
        wruns = max(v[1] for v in ref.values())
        if cmd.get("hmmm"):
            # 런마다 명령을 하나 보내야 한다. 준비 시간은 SendCmd 한 번 값 -
            # WaitVdpCmd + R#17 쓰기 + otir 15 바이트 = 대략 520 T.
            setup = wruns * 520 / Z80_HZ * 1000.0
            print("   VDP 명령으로 그리면: 픽셀 %.1f ms + 명령 준비 %d x 0.15 ="
                  " %.1f ms -> 약 %.1f ms"
                  % (cmd["hmmm"], wruns, setup, cmd["hmmm"] + setup))
        print("   SCREEN 8 은 픽셀만 두 배다(4608 -> 9216 바이트). 나머지 일은 같다.")
        print("   아래는 그중 가장 무거운 화면(%.1f ms)에 얹은 값이다." % worst)
        for v in (1, 3, 4):
            add = 4608 * VAR_T[v] / Z80_HZ * 1000.0
            print("   간격 %5.1f us 면  +%5.1f ms  ->  %6.1f ms (%.1f 프레임)%s"
                  % (VAR_T[v] / Z80_HZ * 1e6, add, worst + add,
                     (worst + add) / 16.67,
                     "   <- 지금 쓰는 간격" if v == 1 else ""))

    print("\n카나리아 (out (n),a = 12 T = 3.35 us. 어떤 모드에서도 너무 빠르다)")
    print("   쓰기 G7 %d, 쓰기 G4 %d, 읽기 G7 %d, 명령중 쓰기 %d  (콜백 = %s)"
          % (canary, canary4, canaryr, canaryc, cbset or "(빈 값)"))
    if canary == 0 and canary4 == 0 and canaryr == 0 and canaryc == 0:
        # 확실히 너무 빠른 접근조차 안 걸린다. 이것은 이 코드의 잘못이 아니라
        # **이 측정으로 답할 수 없는 항목**이다. 그래서 FAIL 로 세지 않고
        # 주의로 남긴다 - 대신 위 '흘림' 칸을 근거로 삼아서는 안 된다.
        print("   주의: 확실히 너무 빠른 접근조차 한 번도 안 걸렸다. 이 openMSX 는")
        print("   화면 표시와의 VRAM 다툼을 흉내내지 않는다. 따라서 위 '흘림' 과")
