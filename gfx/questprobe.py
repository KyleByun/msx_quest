"""SCREEN 8 (GRAPHIC 7) 로 옮길 만한지 재 본다. src/questprobe.asm 참고.

종이에서 안 나오는 것은 **대역폭 하나뿐**이라, 그것만 잰다.

  pal   src/questprobepal.asm 을 만든다 (팔레트 -> GRB332)
  tcl   openMSX 스크립트를 만든다
  check 나온 결과를 읽어 표로 낸다

재는 것 세 가지.

1. 간격 - outi 뒤 nop 을 여섯 가지로 두고 96x96 을 그린 시간을 잰다.
   시간은 롬 안에서 재지 않는다. BlitStart / BlitEnd 브레이크포인트에서
   machine_info time 을 빼면 정확하다.
2. 무결성 - 간격이 모자라면 VDP 가 쓰기를 **조용히 흘린다.** 화면을 찍어서는
   모르므로 VRAM 을 되읽어 0..95 그라데이션과 한 바이트씩 맞춰 본다.
   미리 온 화면을 0xFF 로 지워 두었으므로 흘린 자리는 0xFF 로 남는다.
3. 명령 엔진 좌표 - 양피지 창이 전부 HMMV/HMMM 이라, GRAPHIC 7 에서도 x 가
   픽셀 단위이고 CLR 한 바이트가 픽셀 하나인지 확인해야 한다.
"""
