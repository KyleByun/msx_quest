# --------------------------------------------------------------------------
# 메뉴 커서 - 좌우와 상하가 2x2 격자대로 움직이는가
# --------------------------------------------------------------------------
# 명령이 한 줄에 둘씩 놓이므로 색인의 bit0 이 열, bit1 이 줄이다. 화면만 보고는
# "화살표가 움직였다"까지만 알 수 있어서, 실제로 누른 뒤 MenuSel 을 읽어 본다.
# AskCommand 를 우회하지 않는 유일한 검사다 - 우회하면 입력 처리가 통째로 빠진다.
KEYS = {"left": "0x10", "up": "0x20", "down": "0x40", "right": "0x80"}
CURSOR_PRESSES = ["right", "down", "left", "up", "left", "up"]
CURSOR_WANT = [1, 3, 2, 0, 1, 3]


def cursor_tcl(outdir):
    S = syms()
    w = []
    for i in range(PARTY_N):
        b = S["Party"] + i * PARTY_STRIDE
        w += ["debug write memory %d 10" % (b + P_DEX),
              "debug write memory %d %d" % (b + P_HP, BIG_HP),
              "debug write memory %d %d" % (b + P_MAXHP, BIG_HP)]
    for i in range(MON_N):
        b = S["Monsters"] + i * MON_STRIDE
        hp = BIG_HP if i == 0 else 0
        w += ["debug write memory %d %d" % (b + 1, hp),
              "debug write memory %d %d" % (b + 2, hp)]
    w += ["debug write memory %d 1" % S["MonCount"],
          "debug write memory %d 2" % S["MonKind"],
          "debug write memory %d 1" % S["BattleOn"],
          "debug write memory %d 1" % S["RoundNo"]]
    out = os.path.join(outdir, "cursor.txt").replace(chr(92), "/")
    L = ["# cursor - generated by gfx/quest_turns.py",
         'set ::fh [open "%s" w]' % out,
         "set ::go 0",
         "set ::sel {}",
         "after time 7 { %s ; set ::go 1 }" % " ; ".join(w),
         "debug set_bp %d 1 {" % S["MainLoop"],
         "  if {$::go != 1} { return }",
         "  set ::go 2",
         "  set sp [expr [reg sp] - 2]",
         "  debug write memory $sp %d" % (S["MainLoop"] & 0xFF),
         "  debug write memory [expr $sp + 1] %d" % (S["MainLoop"] >> 8),
         "  reg sp $sp",
         "  reg pc %d" % S["BattleRound"],
         "}"]
    t = 8.0
    for name in CURSOR_PRESSES:                 # 누르고 떼고, 가라앉은 뒤에 읽는다
        L += ["after time %.2f { keymatrixdown 8 %s }" % (t, KEYS[name]),
              "after time %.2f { keymatrixup 8 %s }" % (t + 0.15, KEYS[name]),
              "after time %.2f { lappend ::sel [debug read memory %d] }"
              % (t + 0.35, S["MenuSel"])]
        t += 0.5
    L += ["after time %.2f {" % t,
          '  puts $::fh "sel $::sel"',
          '  puts $::fh "hero [debug read memory %d]"' % S["MenuHero"],
          "  close $::fh ; exit",
          "}"]
    open(os.path.join(outdir, "cursor.tcl"), "w",
         encoding="ascii", newline="\n").write("\n".join(L) + "\n")
    print("wrote cursor.tcl")


def cursor_check(outdir):
    txt = {}
    for line in open(os.path.join(outdir, "cursor.txt")).read().split("\n"):
        if line.strip():
            k, _, v = line.partition(" ")
            txt[k] = v.strip()
    sel = [int(v) for v in txt["sel"].split()]
    ok = sel == CURSOR_WANT
    for name, g, wv in zip(CURSOR_PRESSES, sel, CURSOR_WANT):
        print("   %-6s -> %s%s" % (name, g, "" if g == wv else "   기대 %d" % wv))
    print("cursor  %s" % ("OK" if ok else "MISMATCH (기대 %s)" % CURSOR_WANT))
    print("PASS" if ok else "FAIL")
    return 0 if ok else 1


# --------------------------------------------------------------------------
# 도망(FLEE) - 굴림이 정말 d20 + 민첩 보정인가
# --------------------------------------------------------------------------
# 방어만 검사하고 있었더니 도망의 굴림이 통째로 틀린 채로 지나갔다. RandMod 가
# 면 수를 **C** 로 받는데 A 에 넣고 있었고, RandMod 가 BC 를 뭉개는 것도 놓쳤다.
# 실측 C=0, A=85 - 12 를 넘으니 도망이 거의 언제나 성공했다.
#
# 주사위를 굴리는 명령이라 결과가 확정적이지 않지만 **입력은 확정적이다.**
# RollDie 에 들어가는 면 수가 20 인지, 더해지는 값이 민첩 보정인지를 본다.
FLEE_DEX = 18                   # 보정 +4 (AbilMod 표)
FLEE_MOD = 4
CMD_FLEE = 2


def flee_tcl(outdir):
    S = syms()
    w = []
    for i in range(PARTY_N):
        b = S["Party"] + i * PARTY_STRIDE
        w += ["debug write memory %d %d" % (b + P_DEX, FLEE_DEX),
              "debug write memory %d %d" % (b + P_HP, BIG_HP),
              "debug write memory %d %d" % (b + P_MAXHP, BIG_HP),
              "debug write memory %d 30" % (b + P_AC)]
    for i in range(MON_N):
        b = S["Monsters"] + i * MON_STRIDE
        hp = BIG_HP if i == 0 else 0
        w += ["debug write memory %d %d" % (b + 1, hp),
              "debug write memory %d %d" % (b + 2, hp)]
    w += ["debug write memory %d 1" % S["MonCount"],
          "debug write memory %d 2" % S["MonKind"],
          "debug write memory %d 1" % S["BattleOn"],
          "debug write memory %d 1" % S["RoundNo"]]
    out = os.path.join(outdir, "flee.txt").replace(chr(92), "/")
    L = ["# flee - generated by gfx/quest_turns.py",
         'set ::fh [open "%s" w]' % out,
         "set ::go 0",
         "set ::n 0",
         "set ::sides 0",
         "set ::roll 0",
         "after time 7 { %s ; set ::go 1 }" % " ; ".join(w),
         "debug set_bp %d 1 {" % S["AskCommand"],      # 모두 도망을 고른 셈
         "  debug write memory %d [reg a]" % S["MenuHero"],
         "  set sp [reg sp]",
         "  set lo [debug read memory $sp]",
         "  set hi [debug read memory [expr $sp + 1]]",
         "  reg sp [expr $sp + 2]",
         "  reg pc [expr $lo + $hi * 256]",
         "  reg a %d" % CMD_FLEE,
         "}",
         # RollDie 로 들어갈 때의 C 가 면 수다
         "debug set_bp %d 1 { set ::sides [reg c] }" % S["FleeRoll"],
         # add a,b 직전. A 가 굴림, B 가 민첩 보정이어야 한다.
         "debug set_bp %d 1 {" % S["FleeTotal"],
         # FleeTotal 은 add a,b 자리다. A 가 민첩 보정(AbilityMod 가 막 돌려준
         # 값), B 가 굴림이다. 처음에 이 둘을 거꾸로 읽어서 롬이 맞는데 검사가
         # 틀렸다 - A 가 4 로 고정이고 B 가 흔들리는 것을 보고 알았다.
         '  puts $::fh "flee sides=$::sides mod=[reg a] roll=[reg b]"',
         "  flush $::fh",
         "  incr ::n",
         "  if {$::n >= 6} { close $::fh ; exit }",
         "}",
         "debug set_bp %d 1 {" % S["MainLoop"],
         "  if {$::go != 1} { return }",
         "  set ::go 2",
         "  set sp [expr [reg sp] - 2]",
         "  debug write memory $sp %d" % (S["MainLoop"] & 0xFF),
         "  debug write memory [expr $sp + 1] %d" % (S["MainLoop"] >> 8),
         "  reg sp $sp",
         "  reg pc %d" % S["BattleRound"],
         "}",
         "after time 16 { close $::fh ; exit }"]
    open(os.path.join(outdir, "flee.tcl"), "w",
         encoding="ascii", newline="\n").write("\n".join(L) + "\n")
    print("wrote flee.tcl")


def flee_check(outdir):
    rows = []
    for line in open(os.path.join(outdir, "flee.txt")).read().split("\n"):
        if line.startswith("flee "):
            d = dict(kv.split("=") for kv in line.split()[1:])
            rows.append((int(d["sides"]), int(d["roll"]), int(d["mod"])))
    # sides=20, roll=1..20, mod=민첩 보정
    if not rows:
        print("도망 굴림을 한 번도 못 잡았다")
        return 1
    bad = 0
    for sides, roll, mod in rows:
        ok = sides == 20 and 1 <= roll <= 20 and mod == FLEE_MOD
        if not ok:
            bad += 1
        print("   면 수 %-3d 굴림 %-3d 민첩보정 %-3d  %s"
              % (sides, roll, mod, "OK" if ok else
                 "MISMATCH (면 수 20, 굴림 1~20, 보정 %d 이어야 함)" % FLEE_MOD))
    print("flee  %d 번 중 %d 번 어긋남" % (len(rows), bad))
    print("PASS" if bad == 0 else "FAIL")
    return 0 if bad == 0 else 1


