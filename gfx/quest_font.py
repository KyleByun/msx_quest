FIRST = 32          # 공백
LAST = 90           # 'Z'
CELL_W = 6          # 다음 글자까지의 간격
CELL_H = 8


def glyph_bytes(ch):
    """한 글자를 8 바이트로. 비트 7 이 왼쪽 끝이다."""
    rows = GLYPHS.get(ch)
    if rows is None:
        rows = GLYPHS["?"]
    out = []
    for r in rows:
        b = 0
        for i, c in enumerate(r):
            if c != " ":
                b |= 0x80 >> i
        out.append(b)
    out.append(0)                       # 여덟째 줄은 늘 비어 있다 (줄 간격)
    return out


def font_data():
    data = []
    for code in range(FIRST, LAST + 1):
        data += glyph_bytes(chr(code))
    return data


if __name__ == "__main__":
    from PIL import Image
    cols = 16
    rows = (LAST - FIRST + cols) // cols
    im = Image.new("RGB", (cols * CELL_W, rows * CELL_H), (32, 32, 32))
    px = im.load()
    for i in range(LAST - FIRST + 1):
        g = glyph_bytes(chr(FIRST + i))
        ox, oy = (i % cols) * CELL_W, (i // cols) * CELL_H
        for y in range(8):
            for x in range(CELL_W):
                if g[y] & (0x80 >> x):
                    px[ox + x, oy + y] = (230, 230, 230)
    im.resize((im.width * 6, im.height * 6), Image.NEAREST).save("../build/font.png")
    print("glyphs=%d  bytes=%d  -> build/font.png"
          % (LAST - FIRST + 1, len(font_data())))
